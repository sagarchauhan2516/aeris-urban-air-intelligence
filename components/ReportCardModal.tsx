'use client';

import React from 'react';
import { Download } from 'lucide-react';
import { AQISummary, FamilyAirBrief } from '@/types';

interface ShareReportButtonProps {
  aqi: AQISummary | null;
  brief: FamilyAirBrief | null;
}

export function ShareReportButton({ aqi, brief }: ShareReportButtonProps) {
  const handleDownloadCard = () => {
    if (!aqi || !brief) return;

    // 2x Retina high-definition canvas (1920x1080) for crystal sharp mobile & social sharing
    const canvas = document.createElement('canvas');
    canvas.width = 1920;
    canvas.height = 1080;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    // Background
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, 1920, 1080);

    // Frame Border
    ctx.strokeStyle = '#CBD5E1';
    ctx.lineWidth = 4;
    ctx.strokeRect(40, 40, 1840, 1000);

    // Top Header Banner
    ctx.fillStyle = '#0F172A';
    ctx.font = 'bold 38px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText('AERIS · DAILY HOUSEHOLD AIR QUALITY DOSSIER', 90, 130);

    ctx.fillStyle = '#64748B';
    ctx.font = '30px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(`${aqi.city} · ${new Date().toLocaleDateString(undefined, { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })}`, 90, 185);

    // NAQI Score Callout
    ctx.fillStyle = aqi.color;
    ctx.font = 'bold 140px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(`${aqi.currentNaqi}`, 90, 360);

    ctx.fillStyle = '#0F172A';
    ctx.font = 'bold 48px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(`India NAQI · ${aqi.category}`, 380, 310);

    ctx.fillStyle = '#475569';
    ctx.font = '28px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(
      `Primary Driver: ${aqi.dominantPollutant}  |  PM2.5: ${aqi.pm25} µg/m³  |  Safe Ventilation: ${aqi.ventilationWindow.label}`,
      380,
      365
    );

    // Headline Box
    ctx.fillStyle = '#F8FAFC';
    ctx.fillRect(90, 430, 1740, 100);
    ctx.strokeStyle = '#E2E8F0';
    ctx.lineWidth = 2;
    ctx.strokeRect(90, 430, 1740, 100);

    ctx.fillStyle = '#1E293B';
    ctx.font = 'bold 30px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(`“${brief.headline.slice(0, 110)}”`, 120, 492);

    // Section Divider
    ctx.strokeStyle = '#E2E8F0';
    ctx.beginPath();
    ctx.moveTo(90, 570);
    ctx.lineTo(1830, 570);
    ctx.stroke();

    // Household Risk Matrix
    ctx.fillStyle = '#64748B';
    ctx.font = 'bold 24px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText('HOUSEHOLD MEMBER RISK ASSESSMENTS', 90, 620);

    let y = 675;
    brief.memberRisks.slice(0, 4).forEach((mr) => {
      // Risk tag
      ctx.fillStyle = '#0F172A';
      ctx.font = 'bold 30px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
      ctx.fillText(`• ${mr.name}`, 90, y);

      ctx.fillStyle = mr.riskLevel === 'critical' ? '#DC2626' : mr.riskLevel === 'high' ? '#EA580C' : '#059669';
      ctx.font = 'bold 24px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
      ctx.fillText(`[${mr.riskLevel.toUpperCase()}]`, 320, y);

      ctx.fillStyle = '#475569';
      ctx.font = '26px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
      ctx.fillText(`Safe Outdoor Slot: ${mr.safeHours}`, 520, y);
      y += 65;
    });

    // Commute Recommendation Bar
    ctx.fillStyle = '#F1F5F9';
    ctx.fillRect(90, 890, 1740, 65);
    ctx.fillStyle = '#334155';
    ctx.font = '24px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(
      `Recommended Commute: ${brief.commuteAdvice.bestMode} — ${brief.commuteAdvice.summary.slice(0, 120)}`,
      120,
      932
    );

    // Footer Watermark
    ctx.fillStyle = '#94A3B8';
    ctx.font = '24px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText('Generated by AERIS · Real-time India CPCB NAQI & Exposure Intelligence Platform', 90, 1005);

    const link = document.createElement('a');
    link.download = `aeris-air-dossier-${aqi.city.toLowerCase().replace(/\s+/g, '-')}.png`;
    link.href = canvas.toDataURL('image/png');
    link.click();
  };

  return (
    <button
      type="button"
      onClick={handleDownloadCard}
      disabled={!aqi || !brief}
      className="inline-flex items-center gap-1.5 text-xs font-medium px-3 py-1.5 rounded-md bg-slate-900 hover:bg-slate-800 text-white transition disabled:opacity-40"
    >
      <Download className="w-3.5 h-3.5" />
      <span>Export Report (2x PNG)</span>
    </button>
  );
}
